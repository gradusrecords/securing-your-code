// Usage: node scripts/build-catalog-html.js path/to/catalog.html
// three.js (r128, devDependency) is inlined so the catalog works offline.
// Writes src/catalog/catalogHtml.ts. The source file (with real model names) is never committed.
const fs = require('fs');
const path = require('path');
const { buildCatalogHtml } = require('./catalogTransform');

const input = process.argv[2];
if (!input) { console.error('usage: node scripts/build-catalog-html.js <catalog.html>'); process.exit(1); }
const threePath = path.join(__dirname, '..', 'node_modules', 'three', 'build', 'three.min.js');
const html = buildCatalogHtml(fs.readFileSync(input, 'utf8'), { threeSource: fs.readFileSync(threePath, 'utf8') });
const target = path.join(__dirname, '..', 'src', 'catalog', 'catalogHtml.ts');
fs.writeFileSync(target, `// Generated by scripts/build-catalog-html.js. Do not edit.\nexport const catalogHtml = ${JSON.stringify(html)};\n`);
console.log(`wrote ${target} (${html.length} chars)`);
